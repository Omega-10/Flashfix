/**
 * Checks whether an email address uses a disposable/temporary email domain.
 * Supports root and subdomains (e.g. "user@sub.mailinator.com").
 */
export function isDisposableEmail(email: string): boolean {
  if (!email || typeof email !== 'string') return false;
  const parts = email.toLowerCase().trim().split('@');
  if (parts.length !== 2) return false;
  const host = parts[1];
  if (DISPOSABLE_EMAIL_DOMAINS.has(host)) return true;

  // Check parent domains (e.g. for sub.mailinator.com)
  const segments = host.split('.');
  for (let i = 1; i < segments.length - 1; i++) {
    const parent = segments.slice(i).join('.');
    if (DISPOSABLE_EMAIL_DOMAINS.has(parent)) return true;
  }
  return false;
}
